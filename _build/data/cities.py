def page(city):
    """Собирает описание гео-страницы из данных города."""
    name = city["name"]
    name_in = city["name_in"]
    return {
        "slug": "vilochnye-pogruzchiki-" + city["slug"],
        "title": city["title"],
        # Длина description держится в 150–160 символах, а названия городов
        # различаются по длине вдвое — у кого не попадает в шаблон, тот несёт
        # своё описание (см. Серов). Проверка ловит выход за диапазон.
        "description": city.get("description") or (
            "Подбор вилочного погрузчика в {}: электрические, дизельные и газобаллонные "
            "модели. Сравним варианты и подскажем, что подойдёт вашему складу."
        ).format(name_in),
        "h1": "Вилочные погрузчики в {}".format(name_in),
        "breadcrumb": name,
        "city": name,
        "city_in": name_in,
        "unique": city["unique"],
        "faq": city["faq"],
    }

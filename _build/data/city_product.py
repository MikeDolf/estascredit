"""Слой уникализации: абзац и вопросы, своими для каждой пары товар+город.

Без него сетка товар × город — это дубли, и весь тираж работает против себя.
Абзац подставляется ПЕРВЫМ в основной текст, вопросы — ПЕРВЫМИ в FAQ.

Правило: писать по существу этого города и этого товара — логистическое плечо,
чем занят регион, какие условия эксплуатации. Общие слова, куда можно
подставить любой другой город, уникальности не дают, даже если текст формально
разный. Это ровно та ошибка, из-за которой на первом проекте уникальность
выросла с 2% до 9% вместо ожидаемых 13%.
"""

_NOTES: dict[tuple[str, str], str] = {}
_FAQS: dict[tuple[str, str], list[tuple[str, str]]] = {}


def note(city: str, product: str, text: str) -> None:
    key = (city, product)
    assert key not in _NOTES, f"Абзац для {key} уже задан — молча перезаписывать нельзя"
    _NOTES[key] = text.strip()


def ask(city: str, product: str, question: str, answer: str) -> None:
    key = (city, product)
    bucket = _FAQS.setdefault(key, [])
    existing = {q for q, _ in bucket}
    assert question not in existing, f"Вопрос «{question}» для {key} уже задан"
    bucket.append((question.strip(), answer.strip()))


def get_note(city: str, product: str) -> str | None:
    return _NOTES.get((city, product))


def get_faq(city: str, product: str) -> list[tuple[str, str]]:
    return _FAQS.get((city, product), [])


def coverage(pairs: list[tuple[str, str]]) -> dict[str, int]:
    """Сколько пар сетки уже уникализировано. Печатается при каждой сборке."""
    with_note = sum(1 for c, p in pairs if (c, p) in _NOTES)
    with_faq = sum(1 for c, p in pairs if len(_FAQS.get((c, p), [])) >= 3)
    return {"всего пар": len(pairs), "с абзацем": with_note, "с 3+ вопросами": with_faq}



const published = new Set(articles.map((a) => a.slug));

/**
 * План на 80 статей — тексты уже ссылаются на будущие материалы. Пока статья
 * не опубликована, ссылку на неё разворачиваем в обычный текст: битые
 * внутренние ссылки хуже, чем их отсутствие. Как только статья появляется
 * в `articles`, ссылка включается сама.
 */
export function linkOnlyPublished(markdown: string): string {
  return markdown.replace(
    /\[([^\]]+)\]\(\/articles\/([a-z0-9-]+)\/\)/g,
    (whole, label: string, slug: string) => (published.has(slug) ? whole : label),
  );
}

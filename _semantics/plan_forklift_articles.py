import pickle, re, collections

res = pickle.load(open("classified.pkl","rb"))
clean = [x for x in res if not x["noise"]]
V = [x for x in clean if x["machine"]=="вилочный"]

def has(p,*ws):
    return any(w in p for w in ws)

def ton(p, n):
    # "N тонн" с границей слева (не часть большего числа) и не "до N тонн"-конфликтов.
    return re.search(rf'(?<!\d){n}\s*(?:,5\s*)?тонн', p) is not None

def word(p, w):
    return re.search(rf'(?<![а-яё]){w}(?![а-яё])', p) is not None

V = [x for x in V if not has(x['p'],'сдать на права','экзамен на права','права категории',
     'обучение на погрузчик','курсы на погрузчик','удостоверение тракториста')]

assigned = set()
articles = []

def take(name, cluster, predicate, note=""):
    picked = [x for x in V if id(x) not in assigned and predicate(x['p'])]
    for x in picked: assigned.add(id(x))
    total = sum(x['e'] for x in picked)
    articles.append(dict(name=name, cluster=cluster, items=picked, total=total, note=note))
    return picked


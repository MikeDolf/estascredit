print("Сумма по статьям:", grand, " / Весь чистый вилочный кластер:", sum(x['e'] for x in V))

seen=collections.Counter()
for a in articles:
    for x in a['items']: seen[x['p']]+=1
dupes=[p for p,c in seen.items() if c>1]
print("Дублей фраз между статьями:", len(dupes))

# -*- coding: utf-8 -*-
import pickle, re, collections
G = pickle.load(open("groups.pkl","rb"))

def has(p, *ws): return any(w in p for w in ws)

# --- мусор: трафик, который никогда не станет заявкой ---------------------
NOISE = {
 "работа":("вакансия","вакансии","зарплата","резюме","требуется","подработка","работа "),
 "обучение":("обучение","курсы","удостоверение","корочк","экзамен","билеты","тесты",
             "права на","категория","переподготовка","техминимум","птм","аттестация"),
 "игры":("игрушка","игрушеч","детск","лего","lego","майнкрафт","minecraft","gta","симулятор",
         "игра","игры","мод ","раскраск","мультик","мультфильм","мягкая"),
 "охрана труда":("охране труда","охрана труда","инструкция по охране","должностная",
                 "техника безопасности","журнал","приказ","бирка","стропальщик"),
 "инфо-мусор":("скачать","торрент","бесплатно","реферат","презентация","википедия","что такое",
               "это что","своими руками","чертеж","3d модель","фото ","картинки","видео"),
}
# --- тип техники ----------------------------------------------------------
def machine(p):
    if has(p,"экскаватор"): return "экскаватор-погрузчик"
    if has(p,"фронтальн"):  return "фронтальный"
    if has(p,"телескопич","телехендлер"): return "телескопический"
    if has(p,"бобкэт","бобкат","bobcat","мини погрузчик","минипогрузчик","мини-погрузчик"):
        return "мини-погрузчик"
    if has(p,"бульдозер","грейдер","самосвал","автокран","трактор","комбайн","каток"):
        return "прочая техника"
    if has(p,"рохл","гидравлическая тележка","тележка гидравлическ","гидравлическ тележ"):
        return "рохля"
    if has(p,"штабел"):     return "штабелёр"
    if has(p,"ричтрак","ричстакер"): return "ричтрак"
    if has(p,"электротележ","самоходная тележ","тележка самоходн","транспортировщик"):
        return "электротележка"
    if has(p,"вилочн","автопогрузч","вилочный","cpcd","cpd","cpqd"): return "вилочный"
    if has(p,"погрузчик","погрузчиков","погрузчика"): return "погрузчик без уточнения"
    return "не про погрузчики"

# --- интент ---------------------------------------------------------------
def intent(p):
    if has(p,"аренд","прокат","в аренду"):            return "аренда"
    if has(p,"запчаст","ремонт","неисправн","ошибк","то ","обслуживан","масло",
            "фильтр","гидроцилиндр","цепь","шины","аккумулятор","мачта","вилы",
            "каретка","редуктор","двигател","насос","сальник","подшипник"):
        return "запчасти и сервис"
    if has(p,"навесн","захват","ротатор","кантователь","ковш","сайдшифт","позиционер",
            "снегоотвал","траверс","удлинител"):                return "навесное"
    if has(p,"купить","цена","стоимость","продажа","заказать","прайс","недорого",
            "дешев","бу ","б у","с пробегом","новый","лизинг","рассрочк","кредит"):
        return "коммерческий"
    if has(p,"как выбрать","какой","сравнен","рейтинг","отзыв","лучше","что лучше",
            "чем отлич","плюсы","минусы"):                      return "выбор"
    if has(p,"характеристик","грузоподъем","габарит","вес ","размер","высота подъема",
            "расход","мощность","скорость","радиус"):           return "характеристики"
    if has(p,"растаможк","пошлин","тн вэд","утилизацион","ввоз","импорт"): return "импорт"
    if has(p,"псм","паспорт самоходн","гостехнадзор","регистрац","сертификац",
            "тр тс","декларац","учет"):                         return "документы"
    return "прочее"

URAL = ("екатеринбург","свердловск","нижний тагил","нижнем тагиле","каменск","первоуральск",
        "серов","верхняя пышма","верхней пышме","березовск","асбест","ревда","полевской",
        "новоуральск","краснотурьинск","заречный","реж","алапаевск","ирбит","сухой лог",
        "богданович","качканар","лесной","кушва","тавда","красноуфимск","челябинск","пермь",
        "перми","тюмень","тюмени","курган","уфа","уфе","магнитогорск","златоуст","миасс",
        "сургут","нижневартовск","ижевск","оренбург","нижнем","тагил")

res=[]
for k,v in G.items():
    p=v["phrase"]
    n=None
    for label,pats in NOISE.items():
        if has(p,*pats): n=label; break
    m=machine(p)
    res.append(dict(k=k, p=p, e=v["exact"], b=v["broad"], forms=v["forms"],
                    noise=n, machine=m, intent=intent(p),
                    ural=any(c in p for c in URAL)))
pickle.dump(res, open("classified.pkl","wb"))

def agg(items): return len(items), sum(x["e"] for x in items)
print("ВСЕГО: %d запросов, %d показов\n"%agg(res))
print("=== МУСОР ===")
for label in list(NOISE)+[None]:
    it=[x for x in res if x["noise"]==label]
    if it: print(f"  {str(label or 'чистые'):14} {len(it):7} запросов {sum(x['e'] for x in it):8} показов")
clean=[x for x in res if not x["noise"]]
print("\n=== ТИП ТЕХНИКИ (без мусора) ===")
by=collections.defaultdict(list)
for x in clean: by[x["machine"]].append(x)
for m in sorted(by,key=lambda m:-sum(x["e"] for x in by[m])):
    n,f=agg(by[m]); print(f"  {m:26} {n:7} запросов {f:8} показов")
